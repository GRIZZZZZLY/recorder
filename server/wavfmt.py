"""Формат принятого WAV: сколько байт PCM приходится на секунду звука.

Шкала времени в проекте считается из размера файла, а не из ответа Deepgram:
размер есть у любой части, включая нерасшифрованную. Пока диктофон был один и
писал моно, множитель был константой. С Recorder RevA микрофона два, и та же
часть той же длины весит вдвое больше — константа растянула бы ленту дня и
волну ровно вдвое, ничего при этом не сломав заметно.

Поэтому формат берётся из заголовка самого файла и запоминается при приёмке.
Заголовок не читается — возвращаем None, и вызывающий остаётся на прежнем
моно-значении: все части, принятые до этой правки, именно моно и есть.
"""
import contextlib
import wave

# Границы здравого смысла для (частота x каналы x байт на отсчёт). Ниже —
# 4 кГц моно 8 бит, выше — 96 кГц стерео 32 бита с запасом. Заголовок приходит
# с устройства, и битое число здесь молча исказило бы всю шкалу разговора:
# лучше отказаться от значения, чем поверить в часовую часть из пяти минут.
MIN_BYTES_PER_SECOND = 4000
MAX_BYTES_PER_SECOND = 1_000_000


def bytes_per_second(path):
    """Байт PCM в секунде по заголовку файла. None — заголовок не прочитан."""
    try:
        with contextlib.closing(wave.open(str(path), "rb")) as handle:
            value = (handle.getframerate()
                     * handle.getnchannels()
                     * handle.getsampwidth())
    except (wave.Error, EOFError, OSError):
        return None
    if not MIN_BYTES_PER_SECOND <= value <= MAX_BYTES_PER_SECOND:
        return None
    return value
