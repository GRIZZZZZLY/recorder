// Arduino вставляет автоматические прототипы в начало объединённого файла,
// раньше тела Uploader.ino. Поэтому тип результата объявлен здесь и
// подключается из главного скетча — иначе прототип sendPart не компилируется.
#pragma once

// Итог одной попытки отправки части.
//   SEND_OK    — сервер подтвердил размер и контрольную сумму
//   SEND_RETRY — временная помеха: сеть, таймаут, 5xx, искажение при передаче
//   SEND_FATAL — повтор не поможет: токен, битый запрос, конфликт данных
enum SendResult { SEND_OK, SEND_RETRY, SEND_FATAL };
